function name(doc: DocumentNode) {
  return (doc.definitions.find(d => d.kind === 'OperationDefinition') as OperationDefinitionNode).name?.value
}
const query = vi.fn(async (doc: DocumentNode, _variables?: Record<string, unknown>): Promise<Record<string, unknown>> => {
  if (name(doc) === 'WorkOpsGuidanceProjects') return { workOps: { projects: { all: [{ id: 'project-1', name: 'Core', key: 'CORE' }] } } }
  if (name(doc) === 'ImportWorkOpsSkill') return { workOps: { guidance: { importSkill: { phase: 'INVESTIGATION', name: 'custom-investigation', description: 'Use for debugging', markdown: '# Diagnose', inherited: false } } } }
  if (name(doc) === 'ExportWorkOpsSkill') return { workOps: { guidance: { exportSkill: '---\nname: workops-investigation\ndescription: Use for investigation\n---\n# INVESTIGATION' } } }
  return { workOps: { guidance: { effective: guidance() } } }
})
