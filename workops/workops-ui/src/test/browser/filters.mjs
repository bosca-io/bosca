import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { launchTestBrowser } from '../../../../../gradle/bml-test-browser.mjs';

const base = process.env.ATLAS_WORKOPS_TEST_URL;
assert.ok(base && ['localhost', '127.0.0.1'].includes(new URL(base).hostname));
const owned = await launchTestBrowser(0), context = owned.connection.contexts()[0], page = context.pages()[0];
const reports = resolve('build/reports/filters-browser', new URL(base).port);
await mkdir(reports, { recursive: true });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
const name = 'Browser saved filter', source = 'project = UI ORDER BY modified DESC';
const row = () => page.getByRole('row').filter({ has: page.getByRole('link', { name, exact: true }) });
const pending = () => page.waitForFunction(() => !document.querySelector('[data-bml-action-pending]'));
const checkQueryFocus = async dialog => {
  const editor = dialog.locator('[data-bml-code-editor]');
  await editor.locator('.cm-content').waitFor();
  assert.equal(await editor.locator('.cm-gutters').count(), 0, 'Saved queries use the compact editor without a code-file gutter');
  assert.ok((await editor.boundingBox()).height <= 60, 'A one-line saved query stays compact');
  await dialog.locator('input[name=name]').focus();
  const border = await editor.evaluate(node => getComputedStyle(node).borderColor);
  await editor.locator('.cm-content').focus();
  const focused = await editor.evaluate(node => ({
    border: getComputedStyle(node).borderColor, shadow: getComputedStyle(node).boxShadow,
    innerOutline: getComputedStyle(node.querySelector('.cm-editor')).outlineStyle,
  }));
  assert.notEqual(focused.border, border, 'The rounded field border indicates focus');
  assert.notEqual(focused.shadow, 'none', 'Keyboard focus stays visible');
  assert.equal(focused.innerOutline, 'none', 'Saved queries have no inner rectangular focus box');
};
try {
  await page.goto(base + '/login');
  await page.locator('input[name=identifier]').fill('admin');
  await page.locator('input[name=password]').fill(process.env.ATLAS_WORKOPS_TEST_PASSWORD);
  await page.locator('button[type=submit]').click();
  await page.waitForURL(url => url.pathname !== '/login');
  await page.goto(base + '/workops/tasks?bql=status%20%3D');
  await page.getByRole('alert').filter({ hasText: /query range \d+–\d+/ }).waitFor();
  assert.equal(await page.locator('textarea[name=bql]').inputValue(), 'status =');
  assert.equal(await page.getByText('No tasks found', { exact: true }).count(), 0);
  await page.goto(base + '/workops/filters');
  await page.getByRole('button', { name: 'New filter', exact: true }).click();
  let editing = page.getByRole('dialog', { name: 'New filter', exact: true });
  await editing.waitFor();
  await editing.locator('input[name=name]').fill(name);
  await editing.locator('input[name=description]').fill('A browser-created saved query');
  await editing.locator('.cm-content').waitFor();
  await checkQueryFocus(editing);
  await editing.locator('.cm-content').fill('status =');
  await editing.getByRole('button', { name: 'Save filter', exact: true }).click();
  await editing.getByRole('alert').first().waitFor();
  assert.equal(await editing.locator('textarea[name=source]').inputValue(), 'status =');
  assert.equal(await editing.locator('input[name=name]').inputValue(), name);
  assert.equal(await row().count(), 0);
  await editing.locator('.cm-content').fill(source);
  await editing.getByRole('button', { name: 'Save filter', exact: true }).click();
  await editing.waitFor({ state: 'hidden' });
  await row().waitFor();
  await row().getByRole('button', { name: 'Preview', exact: true }).click();
  const preview = page.getByRole('dialog', { name: 'Filter preview', exact: true });
  await preview.waitFor();
  assert.ok(await preview.locator('a[href^="/workops/tasks/"]').count() > 0);
  const all = preview.getByRole('link', { name: 'View all results', exact: true });
  assert.equal(await all.getAttribute('href'), `/workops/tasks?bql=${encodeURIComponent(source)}`);
  await all.click();
  await page.waitForURL(url => url.pathname === '/workops/tasks');
  assert.equal(new URL(page.url()).searchParams.get('bql'), source);
  assert.equal(await page.evaluate(() => localStorage.getItem('workops-tasks-bql')), source);
  await page.goto(base + '/workops/tasks');
  await page.waitForURL(url => url.searchParams.get('bql') === source);
  const explicit = 'ORDER BY created DESC';
  await page.goto(base + '/workops/tasks?bql=' + encodeURIComponent(explicit));
  assert.equal(await page.locator('textarea[name=bql]').inputValue(), explicit);
  assert.equal(await page.evaluate(() => localStorage.getItem('workops-tasks-bql')), explicit);
  await page.locator('[data-bml-code-editor] .cm-content').waitFor();
  await page.getByRole('button', { name: 'New task', exact: true }).focus();
  await page.keyboard.press('/');
  assert.equal(await page.locator('[data-bml-code-editor] [role=textbox]').evaluate(element => element === document.activeElement), true);
  await page.locator('[data-bml-code-editor] .cm-content').fill(source);
  await page.locator('[data-bml-code-editor] .cm-content').press('Control+Enter');
  await page.waitForURL(url => url.searchParams.get('bql') === source);
  await page.getByRole('button', { name: 'Clear query', exact: true }).click();
  await page.waitForURL(url => url.searchParams.has('bql') && url.searchParams.get('bql') === '');
  assert.equal(await page.locator('textarea[name=bql]').inputValue(), '');
  assert.equal(await page.evaluate(() => localStorage.getItem('workops-tasks-bql')), null);
  await page.goto(base + '/workops/filters');
  await row().getByRole('button', { name: /^Edit / }).click();
  editing = page.getByRole('dialog', { name: 'Edit filter', exact: true });
  await editing.waitFor();
  await editing.locator('input[name=description]').fill('Updated browser description');
  await editing.getByRole('button', { name: 'Save filter', exact: true }).click();
  await editing.waitFor({ state: 'hidden' });
  await row().getByText('Updated browser description', { exact: true }).waitFor();
  for (const appearance of ['dark', 'light']) {
    await context.addCookies([{ name: 'git_ui_appearance', value: appearance, url: base }]);
    for (const width of [1920, 1024, 768, 390]) {
      await page.setViewportSize({ width, height: 1000 });
      await page.goto(base + '/workops/filters');
      await row().waitFor();
      assert.equal(await page.locator('html').getAttribute('data-theme'), appearance);
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
      await page.screenshot({ path: resolve(reports, `${appearance}-${width}-list.png`), fullPage: true });
      await page.getByRole('button', { name: 'New filter', exact: true }).click();
      const creating = page.getByRole('dialog', { name: 'New filter', exact: true });
      await creating.waitFor();
      await checkQueryFocus(creating);
      await page.screenshot({ path: resolve(reports, `${appearance}-${width}-new-focused.png`), fullPage: true });
      await creating.getByRole('button', { name: 'Cancel', exact: true }).click();
      await creating.waitFor({ state: 'hidden' });
      await row().getByRole('button', { name: /^Edit / }).click();
      editing = page.getByRole('dialog', { name: 'Edit filter', exact: true });
      await editing.waitFor();
      const box = await editing.boundingBox();
      assert.ok(box.x >= -1 && box.x + box.width <= width + 1 && box.y >= -1 && box.y + box.height <= 1001, JSON.stringify(box));
      assert.equal(await editing.evaluate(element => getComputedStyle(element).backgroundColor), appearance === 'light' ? 'rgb(255, 255, 255)' : 'rgb(16, 19, 28)');
      await checkQueryFocus(editing);
      await page.screenshot({ path: resolve(reports, `${appearance}-${width}-edit.png`), fullPage: true });
      await editing.locator('input[name=name]').press('Escape');
      await editing.waitFor({ state: 'hidden' });
      await pending();
      assert.equal(await row().getByRole('button', { name: /^Edit / }).evaluate(element => element === document.activeElement), true);
    }
  }
  await row().getByRole('button', { name: /^Delete / }).click();
  const deleting = page.getByRole('dialog', { name: 'Delete saved filter', exact: true });
  await deleting.waitFor();
  await deleting.getByRole('button', { name: 'Delete saved filter', exact: true }).click();
  assert.equal(await deleting.isVisible(), true);
  await deleting.getByRole('checkbox', { name: 'Delete this saved filter', exact: true }).check();
  await deleting.getByRole('button', { name: 'Delete saved filter', exact: true }).click();
  await deleting.waitFor({ state: 'hidden' });
  await page.getByText('Saved filter deleted.', { exact: true }).waitFor();
  assert.equal(await row().count(), 0);
  assert.deepEqual(errors, []);
  console.log('Saved filter create, validation, edit, preview, run, delete, focus and palettes passed.');
} catch (error) {
  await page.screenshot({ path: resolve(reports, 'failure.png'), fullPage: true }).catch(() => {});
  console.error(await page.locator('body').innerText().catch(() => 'Page unavailable'));
  throw error;
} finally { await owned.close(); }
