import assert from 'node:assert/strict';
import { mkdir } from 'node:fs/promises';
import { resolve } from 'node:path';
import { launchTestBrowser } from '../../../../../gradle/bml-test-browser.mjs';

const base = process.env.ATLAS_WORKOPS_TEST_URL;
assert.ok(base && ['localhost', '127.0.0.1'].includes(new URL(base).hostname));
const owned = await launchTestBrowser(0), context = owned.connection.contexts()[0], page = context.pages()[0];
const reports = resolve('build/reports/inbox-browser', new URL(base).port);
await mkdir(reports, { recursive: true });
const errors = [];
page.on('pageerror', error => errors.push(error.message));
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()); });
const pending = () => page.waitForFunction(() => !document.querySelector('[data-bml-action-pending]'));
const schema = () => page.locator('[data-bml-schema-form]');
const tab = name => schema().getByRole('tab', { name, exact: true });
const time = property => schema().locator(`[data-schema-property=${property}] input`);
try {
  await page.goto(base + '/login');
  await page.locator('input[name=identifier]').fill('admin');
  await page.locator('input[name=password]').fill(process.env.ATLAS_WORKOPS_TEST_PASSWORD);
  await page.locator('button[type=submit]').click();
  await page.waitForURL(url => url.pathname !== '/login');
  await page.goto(base + '/workops/inbox');
  const first = page.locator('.workops-notification').filter({ has: page.locator('a[href^="/workops/tasks/"]') }).first();
  await first.waitFor();
  const id = await first.getAttribute('data-notification-id');
  const destination = await first.locator('a.workops-notification-body').getAttribute('href');
  assert.ok(id && destination);
  await first.locator('a.workops-notification-body').click();
  await page.waitForURL(url => url.pathname === destination);
  await page.locator('[data-workops-task-detail]').waitFor();
  await page.goto(base + '/workops/inbox?tab=all');
  const read = page.locator(`[data-notification-id="${id}"]`);
  await read.waitFor();
  assert.equal(await read.getByText('Unread', { exact: true }).count(), 0);
  assert.equal(await read.getByRole('button', { name: 'Mark read', exact: true }).count(), 0);
  await page.goto(base + '/workops/inbox?tab=preferences');
  await schema().waitFor();
  assert.equal(await schema().getByRole('switch', { name: 'Watch tasks I create', exact: true }).isChecked(), true);
  await schema().getByRole('switch', { name: 'Watch tasks I create', exact: true }).uncheck();
  await tab('Delivery channels').click();
  const inApp = schema().getByRole('group', { name: 'Task created', exact: true }).getByRole('switch', { name: 'In-app', exact: true });
  const email = schema().getByRole('group', { name: 'Task created', exact: true }).getByRole('switch', { name: 'Email', exact: true });
  assert.equal(await inApp.isChecked(), true);
  assert.equal(await email.isChecked(), true);
  assert.equal(await schema().getByRole('group', { name: 'Task created', exact: true }).getByRole('switch', { name: 'Slack', exact: true }).isChecked(), false);
  await inApp.uncheck(); await email.uncheck();
  await tab('Digest and quiet hours').click();
  await schema().getByRole('switch', { name: 'Daily digest email', exact: true }).check();
  await time('dndStartLocal').fill('bad-time');
  await time('dndEndLocal').fill('08:00');
  await page.getByRole('button', { name: 'Save preferences', exact: true }).click();
  await page.getByRole('alert').filter({ hasText: 'Enter the quiet-hours start' }).waitFor();
  assert.equal(await time('dndStartLocal').inputValue(), 'bad-time');
  await tab('Delivery channels').click();
  assert.equal(await schema().getByRole('group', { name: 'Task created', exact: true }).getByRole('switch', { name: 'In-app', exact: true }).isChecked(), false);
  await tab('Digest and quiet hours').click();
  await time('dndStartLocal').fill('22:00');
  await page.getByRole('button', { name: 'Save preferences', exact: true }).click();
  await page.getByText('Notification preferences saved.', { exact: true }).waitFor();
  await page.reload();
  await tab('Watch settings').waitFor();
  assert.equal(await schema().getByRole('switch', { name: 'Watch tasks I create', exact: true }).isChecked(), false);
  await tab('Delivery channels').click();
  assert.equal(await schema().getByRole('group', { name: 'Task created', exact: true }).getByRole('switch', { name: 'In-app', exact: true }).isChecked(), false);
  assert.equal(await schema().getByRole('group', { name: 'Task created', exact: true }).getByRole('switch', { name: 'Email', exact: true }).isChecked(), false);
  assert.equal(await schema().getByRole('group', { name: 'Task updated', exact: true }).getByRole('switch', { name: 'Email', exact: true }).isChecked(), true);
  await tab('Digest and quiet hours').click();
  assert.equal(await time('dndStartLocal').inputValue(), '22:00');
  assert.equal(await time('dndEndLocal').inputValue(), '08:00');
  await time('dndStartLocal').fill('23:00');
  await page.getByRole('button', { name: 'Refresh inbox', exact: true }).click();
  await pending();
  assert.equal(await time('dndStartLocal').inputValue(), '23:00', 'refresh preserves the open preference draft');
  assert.equal(await tab('Digest and quiet hours').getAttribute('aria-selected'), 'true');
  await time('dndStartLocal').fill('22:00');
  for (const appearance of ['dark', 'light']) {
    await context.addCookies([{ name: 'git_ui_appearance', value: appearance, url: base }]);
    for (const width of [1920, 1024, 768, 390]) {
      await page.setViewportSize({ width, height: 1000 });
      await page.goto(base + '/workops/inbox?tab=preferences');
      await tab('Delivery channels').click();
      assert.equal(await page.locator('html').getAttribute('data-theme'), appearance);
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
      await page.screenshot({ path: resolve(reports, `${appearance}-${width}-preferences.png`), fullPage: true });
      await page.goto(base + '/workops/inbox?tab=all');
      await page.locator('.workops-notification').first().waitFor();
      assert.equal(await page.evaluate(() => document.documentElement.scrollWidth > innerWidth), false);
      await page.screenshot({ path: resolve(reports, `${appearance}-${width}-all.png`), fullPage: true });
    }
  }
  const next = page.getByRole('link', { name: 'Next', exact: true });
  await next.waitFor();
  await next.click();
  await page.waitForURL(url => url.searchParams.get('offset') === '30');
  await page.getByRole('link', { name: 'Previous', exact: true }).click();
  await page.waitForURL(url => url.searchParams.get('offset') === '0');
  await page.getByRole('button', { name: 'Mark all read', exact: true }).click();
  await page.getByText('All notifications marked read.', { exact: true }).waitFor();
  await page.goto(base + '/workops/inbox');
  await page.getByRole('heading', { name: 'All caught up', exact: true }).waitFor();
  assert.deepEqual(errors, []);
  console.log('Inbox read/navigation, preference defaults, opt-outs, retained drafts and responsive palettes passed.');
} catch (error) {
  await page.screenshot({ path: resolve(reports, 'failure.png'), fullPage: true }).catch(() => {});
  console.error(await page.locator('body').innerText().catch(() => 'Page unavailable'));
  throw error;
} finally { await owned.close(); }
