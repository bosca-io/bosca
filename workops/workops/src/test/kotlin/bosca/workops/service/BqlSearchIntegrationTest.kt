    private fun withDb(block: suspend () -> Unit) = runBlocking {
        val mgr = pool.connection()
        try {
            withContext(mgr.asCoroutineContext()) { block() }
        } finally {
            withContext(NonCancellable) { mgr.release() }
        }
    }

    private val ownerId: UUID = UUID.parse("11111111-1111-1111-1111-111111111111")
    private val callerPrincipalId: UUID = UUID.parse("22222222-2222-2222-2222-222222222222")
    private val callerProfileId: UUID = UUID.parse("33333333-3333-3333-3333-333333333333")
    private val otherProfileId: UUID = UUID.parse("44444444-4444-4444-4444-444444444444")

    private suspend fun seedProject(key: String = "BQS"): UUID {
        val portfolio = portfolioService.create(
            PortfolioInput(key = key, name = "$key Portfolio", description = null, ownerProfileId = ownerId)
        )
        val program = programService.create(
            ProgramInput(
                portfolioId = portfolio.id, key = "${key}P", name = "$key Program",
                description = null, ownerProfileId = ownerId,
            )
        )
        val project = projectService.create(
            ProjectInput(
                programId = program.id, key = key, name = "$key Project",
                description = null, ownerProfileId = ownerId,
            )
        )
        return project.id
    }

    private suspend fun createTask(
        projectId: UUID,
        summary: String,
        assigneeProfileId: UUID? = null,
        dueDate: bosca.serialization.OffsetDateTime? = null,
        startDate: bosca.serialization.OffsetDateTime? = null,
    ) = taskService.create(
        CreateTaskInput(
            projectId = projectId,
            summary = summary,
            assigneeProfileId = assigneeProfileId,
            dueDate = dueDate,
            startDate = startDate,
        ),
        actingPrincipalId = callerPrincipalId,
        actingProfileId = callerProfileId,
        reporterProfileId = callerProfileId,
    )

    // ---------------------------------------------------------------
    // TEXT equality — binds BqlBoundType.TEXT via PreparedStatement.setString
    // ---------------------------------------------------------------

    @Test
    fun `text equality filters on exact summary match`() = withDb {
        val projectId = seedProject()
        val target = createTask(projectId, "unique-needle-xyz")
        createTask(projectId, "unrelated task")

        val result = taskQueryService.search(
            """summary = "unique-needle-xyz"""",
            actingProfileId = callerProfileId,
        )
        assertEquals(1, result.rows.size)
        assertEquals(target.id, result.rows.single().id)
    }

    @Test
    fun `text inequality excludes matching summary`() = withDb {
        val projectId = seedProject()
        createTask(projectId, "exclude-me")
        val kept = createTask(projectId, "keep-me")

        val result = taskQueryService.search(
            """summary != "exclude-me"""",
            actingProfileId = callerProfileId,
        )
        val ids = result.rows.map { it.id }
        assertTrue(kept.id in ids)
        assertTrue(result.rows.none { it.summary == "exclude-me" })
    }

    // ---------------------------------------------------------------
    // TEXT ILIKE — binds BqlBoundType.TEXT via setString with % wrapping
    // ---------------------------------------------------------------

    @Test
    fun `text like performs case-insensitive substring search`() = withDb {
        val projectId = seedProject()
        val target = createTask(projectId, "Deploy the WIDGET today")
        createTask(projectId, "nothing relevant")

        val result = taskQueryService.search(
            """summary ~ "widget"""",
            actingProfileId = callerProfileId,
        )
        assertEquals(1, result.rows.size)
        assertEquals(target.id, result.rows.single().id)
        assertEquals(listOf("widget"), result.freeTextTerms)
    }

