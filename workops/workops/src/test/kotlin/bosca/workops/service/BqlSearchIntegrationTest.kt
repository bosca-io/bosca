    @Test
    fun `name references resolve task type status and resolution catalogs`() = withDb {
        val projectId = seedProject("NRC")
        val task = createTask(projectId, "catalog task")
        val taskType = taskTypeRepo.getAll().first { it.id == task.taskTypeId }
        val status = statusRepo.getAll().first { it.id == task.statusId }
        val resolution = resolutionRepo.getAll().first()

        assertEquals(
            task.id,
            taskQueryService.search("type = \"${taskType.name}\"", callerProfileId).rows.single().id,
        )
        assertEquals(
            task.id,
            taskQueryService.search("status = \"${status.name}\"", callerProfileId).rows.single().id,
        )
        assertTrue(taskQueryService.search("resolution = \"${resolution.name}\"", callerProfileId).rows.isEmpty())
    }

