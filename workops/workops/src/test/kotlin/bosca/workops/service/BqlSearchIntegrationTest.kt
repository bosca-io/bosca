    @Test
    fun `name reference resolves priority by name`() = withDb {
        val projectId = seedProject("PRI")
        val t1 = createTask(projectId, "task-a")
        val t2 = createTask(projectId, "task-b")

        // Both tasks share the same default priority (Medium). Searching
        // by that name should return both.
        val result = taskQueryService.search(
            "priority = Medium",
            actingProfileId = callerProfileId,
        )
        val ids = result.rows.map { it.id }.toSet()
        assertTrue(t1.id in ids)
        assertTrue(t2.id in ids)
