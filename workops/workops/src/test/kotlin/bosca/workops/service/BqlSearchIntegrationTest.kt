    @Test
    fun `timestamp filter with created less-than future returns all tasks`() = withDb {
        val projectId = seedProject("TSF")
        createTask(projectId, "alpha")
        createTask(projectId, "beta")

        // All tasks have created_at in the past, so created < endOfWeek()
        // should match them all.
        val result = taskQueryService.search(
            "created < endOfWeek()",
            actingProfileId = callerProfileId,
        )
        assertTrue(result.rows.size >= 2, "expected at least 2 tasks, got ${result.rows.size}")
    }

    @Test
    fun `timestamp filter with created greater-than far-future returns nothing`() = withDb {
        val projectId = seedProject("TSN")
        createTask(projectId, "task-one")

        // Use a future timestamp literal that is clearly after all seeded tasks.
        val result = taskQueryService.search(
            """created > "2099-01-01T00:00:00Z"""",
            actingProfileId = callerProfileId,
        )
        assertEquals(0, result.rows.size)
    }

