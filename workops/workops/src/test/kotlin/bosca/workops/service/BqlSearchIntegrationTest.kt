    @Test
    fun `row mapping preserves structured external references`() = withDb {
        val projectId = seedProject("EXT")
        val task = createTask(projectId, "external reference")
        transaction {
            connection().useStatement(
                "update workops.task set external_references = cast(? as jsonb) where id = ?",
            ) { statement ->
                statement.setString(1, "{\"ticket\":\"SUP-42\"}")
                statement.setObject(2, java.util.UUID.fromString(task.id.toString()))
                statement.executeUpdate()
            }
        }

        val mapped = taskQueryService.search("project = EXT", callerProfileId).rows.single()

        assertEquals("SUP-42", mapped.externalReferences?.jsonObject?.get("ticket")?.jsonPrimitive?.content)
    }

