/**
 * End-to-end integration test exercising [TaskQueryServiceImpl.search]
 * against a real PostgreSQL instance via TestContainers. The suite
 * proves that the hand-rolled [TaskQueryServiceImpl.bindParameter]
 * method correctly binds every [bosca.workops.model.bql.BqlBoundType]
 * variant to a real [java.sql.PreparedStatement]:
 *
 *   1. TEXT equality and ILIKE via `summary = "…"` / `summary ~ "…"`.
 *   2. NAME_REFERENCE resolution via `project = KEY` / `priority = Name`.
 *   3. UUID equality via `assignee = currentUser()`.
 *   4. TIMESTAMP comparison via `created > now()` / `dueDate < now()`.
 *   5. ORDER BY and LIMIT clauses generated by the planner.
 *   6. Compound AND / OR filters with multiple bound parameters.
 *
 * Each test seeds a small number of tasks and asserts that the dynamic
 * SQL round-trips through Postgres without JDBC type errors or silent
 * data corruption.
 */
