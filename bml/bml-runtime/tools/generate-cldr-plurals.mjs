#!/usr/bin/env node
/**
 * Generates the CLDR plural differential fixture: for every language in the
 * bundled plurals.json, the category REAL ICU (Node's Intl.PluralRules) assigns to each count
 * in the sweep. The Kotlin evaluator replays the identical sweep and must agree — no
 * hand-written linguistic expectation exists anywhere in the loop.
 *
 * The sweep covers every residue class the cardinal integer rules can reference: 0..259 covers
 * mod 10 and mod 100 (with the teens twice over), and the million samples cover the Romance
 * and Breton `% 1000000` branches. Category letters: z o t f m x (zero/one/two/few/many/other).
 *
 *   node tools/generate-cldr-plurals.mjs   # rewrites test/parity/cldr-plurals.json
 */
import { readFileSync, writeFileSync } from "node:fs"

const LETTER = { zero: "z", one: "o", two: "t", few: "f", many: "m", other: "x" }
const COUNTS = [...Array.from({ length: 260 }, (_, i) => i), 1000, 1001, 999999, 1000000, 1000001, 2000000, 5000000]

const plurals = JSON.parse(readFileSync(new URL("../../core-bml/src/main/resources/bosca/bml/i18n/plurals.json", import.meta.url)))
// "und" (CLDR root) is excluded: ECMA-402 resolves it to the RUNTIME DEFAULT locale, so Intl
// cannot express root's other-only rule — the Kotlin side's root behavior has its own unit test.
const languages = Object.keys(plurals.supplemental["plurals-type-cardinal"]).filter((l) => l !== "und").sort()

const categories = {}
const skipped = []
for (const language of languages) {
  let rules
  try {
    rules = new Intl.PluralRules(language)
  } catch {
    skipped.push(language) // a tag Node's ICU cannot parse at all
    continue
  }
  categories[language] = COUNTS.map((n) => LETTER[rules.select(n)]).join("")
}

const fixture = {
  comment:
    "GENERATED by tools/generate-cldr-plurals.mjs — real-ICU plural categories per language and count. " +
    "The Kotlin CLDR evaluator (core-bml PluralRules) must match every cell; vitest re-derives this " +
    "to catch drift. Letters: z=zero o=one t=two f=few m=many x=other.",
  cldrVersion: plurals.supplemental.version._cldrVersion,
  nodeIcu: process.versions.icu ?? "unknown",
  counts: COUNTS,
  skipped,
  categories,
}
writeFileSync(new URL("../test/parity/cldr-plurals.json", import.meta.url), JSON.stringify(fixture, null, 1) + "\n")
console.log(`wrote ${Object.keys(categories).length} languages x ${COUNTS.length} counts (skipped: ${skipped.length ? skipped.join(",") : "none"})`)
